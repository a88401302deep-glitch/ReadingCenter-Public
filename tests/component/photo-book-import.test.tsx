it('matches title and author without ISBN and retains the selected book after reopening without importing', async () => {
 vi.stubGlobal('crypto', webcrypto)
 URL.createObjectURL = vi.fn(() => 'blob:photo'); URL.revokeObjectURL = vi.fn()
 const { confirmPhotoBook } = await import('../../src/import/photo-book')
 const repo = createInMemoryRepositories()
 const draft = { title: '同名作品', author: '乙作者', publisher: '', isbn: '', visibleText: '清單' }
 const options = { hash: 'a'.repeat(64), bookId: null, source: '其他', mediaType: 'ebook', allowSameTitle: true }
 const other = await confirmPhotoBook(repo, draft, options)
 const matching = await confirmPhotoBook(repo, { ...draft, author: '甲作者' }, { ...options, hash: 'b'.repeat(64) })
 const before = await repo.books.getAll()
 const queue = new PhotoReviewQueue('author-match-' + crypto.randomUUID()); queues.push(queue)
 const file = new File(['photo'], 'no-isbn.png', { type: 'image/png' })
 Object.defineProperty(file, 'arrayBuffer', { value: async () => new Uint8Array([71]).buffer })
 const added = await queue.add(file)
 await queue.setCandidates(added.id, [{ ...draft, author: '甲作者' }])
 const mounted = render(<PhotoBookImport repositories={repo} queue={queue} onBack={vi.fn()} />)
 const select = await screen.findByLabelText('書庫比對') as HTMLSelectElement
 expect([...select.options].map(option => option.value)).toEqual(['new', matching.id, other.id])
 expect(select.options[1].textContent).toContain('甲作者')
 expect(select.options[2].textContent).toContain('乙作者')
 fireEvent.change(select, { target: { value: matching.id } })
 fireEvent.change(screen.getByLabelText('來源', { exact: true }), { target: { value: '圖書館' } })
 await waitFor(async () => expect((await queue.list())[0].candidates![0]).toMatchObject({ bookId: matching.id, source: '圖書館' }))
 mounted.unmount(); queue.close()
 const reopened = new PhotoReviewQueue(queue.name); queues.push(reopened)
 render(<PhotoBookImport repositories={repo} queue={reopened} onBack={vi.fn()} />)
 await waitFor(() => expect(screen.getByLabelText('書庫比對')).toHaveProperty('value', matching.id))
 expect(screen.getByLabelText('來源', { exact: true })).toHaveProperty('value', '圖書館')
 expect((await reopened.list())[0].image).not.toBeNull()
 expect(await repo.books.getAll()).toEqual(before)
 expect(await repo.readingRecords.getAll()).toEqual([])
}, 15000)
it('reopens a previously confirmed candidate and supplements reading evidence without creating another book', async () => {
 vi.stubGlobal('crypto', webcrypto)
 URL.createObjectURL = vi.fn(() => 'blob:photo'); URL.revokeObjectURL = vi.fn()
 const repo = createInMemoryRepositories(), queue = new PhotoReviewQueue('reading-supplement-' + crypto.randomUUID()); queues.push(queue)
 const file = new File(['photo'], 'already-imported.png', { type: 'image/png' })
 Object.defineProperty(file, 'arrayBuffer', { value: async () => new Uint8Array([81]).buffer })
 const added = await queue.add(file)
 const draft = { title: '已匯入的書', author: '', publisher: '', isbn: '', visibleText: '4小時22分鐘 完讀日期2026/09/30' }
 await queue.setCandidates(added.id, [draft])
 const candidate = (await queue.list())[0].candidates![0]
 const { confirmPhotoBook } = await import('../../src/import/photo-book')
 const book = await confirmPhotoBook(repo, draft, { bookId: null, hash: (await queue.list())[0].hash, source: '讀墨', mediaType: 'ebook', allowSameTitle: false })
 await queue.finish(added.id, book.id, candidate.id)
 const mounted = render(<PhotoBookImport repositories={repo} queue={queue} onBack={vi.fn()} />)
 await screen.findByRole('button', { name: '候選 1：已匯入的書 · 書籍已確認' })
 fireEvent.change(screen.getByLabelText('完讀日期', { exact: true }), { target: { value: '2026-09-30' } })
 fireEvent.change(screen.getByLabelText('累計閱讀時間（分鐘）'), { target: { value: '262' } })
 await waitFor(async () => expect((await queue.list())[0].candidates![0].reading).toMatchObject({ completedOn: '2026-09-30', totalMinutes: '262' }))
 expect(await repo.readingCycles.getAll()).toEqual([])
 mounted.unmount(); queue.close()
 const reopened = new PhotoReviewQueue(queue.name); queues.push(reopened)
 render(<PhotoBookImport repositories={repo} queue={reopened} onBack={vi.fn()} />)
 await waitFor(() => expect(screen.getByLabelText('完讀日期', { exact: true })).toHaveProperty('value', '2026-09-30'))
 expect(screen.getByLabelText('累計閱讀時間（分鐘）')).toHaveProperty('value', '262')
 fireEvent.click(screen.getByRole('button', { name: '確認匯入閱讀紀錄' }))
 await screen.findByText('已確認保存完讀日期與累計閱讀時間；未新增書籍或封面。')
 expect(await repo.books.getAll()).toHaveLength(1)
 expect(await repo.readingRecords.getAll()).toHaveLength(0)
 expect((await repo.readingCycles.getAll())[0]).toMatchObject({ bookId: book.id, reportedDurationMinutes: 262, completionDate: { precision: 'date', completedOn: '2026-09-30' } })
 expect((await reopened.list())[0].candidates![0].savedReadingCycleId).toBeTruthy()
}, 15000)

