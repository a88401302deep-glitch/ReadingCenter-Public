import { expect, test } from './fixtures'

for (const width of [360, 1280]) test(`book editor retains context and fits the dialog at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 780 })
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('清單直接編輯測試')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  const search = page.getByRole('searchbox', { name: '搜尋書庫' })
  await search.fill('直接編輯')
  await page.locator('.book-cover-open').first().click()
  const dialog = page.getByRole('dialog')
  const publication = dialog.locator('.book-detail-publication')
  await publication.locator('summary').click()
  await dialog.evaluate(node => { node.scrollTop = 120 })
  const originalTop = await dialog.evaluate(node => node.scrollTop)
  expect(originalTop).toBeGreaterThan(0)
  const trigger = dialog.getByRole('button', { name: '編輯書籍', exact: true })
  await trigger.evaluate((node: HTMLButtonElement) => node.click())
  const editor = page.locator('.book-form')
  await expect(editor).toBeVisible()
  const bounds = await editor.boundingBox()
  expect(bounds!.x).toBeGreaterThan(0)
  expect(bounds!.y).toBeGreaterThan(0)
  expect(bounds!.x + bounds!.width).toBeLessThan(width)
  expect(bounds!.y + bounds!.height).toBeLessThan(780)
  await expect(editor.getByLabel('出版書名', { exact: true })).toBeFocused()
  const titleTop = await editor.getByLabel('出版書名', { exact: true }).boundingBox()
  const authorTop = await editor.getByLabel('作者（每行一位）', { exact: true }).boundingBox()
  expect(authorTop!.y).toBeGreaterThan(titleTop!.y)
  await expect(page.getByRole('dialog')).toHaveCount(1)
  await editor.getByLabel('書籍備註').fill('https://example.com/' + 'longnote'.repeat(40))
  await editor.getByLabel('書籍字數').fill('123456')
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(1)
  const inlineSave = editor.getByRole('button', { name: '儲存', exact: true })
  const inlineBounds = await inlineSave.boundingBox()
  expect(inlineBounds!.y).toBeGreaterThanOrEqual(0)
  expect(inlineBounds!.y + inlineBounds!.height).toBeLessThanOrEqual(780)
  await inlineSave.click()
  await expect(editor).toHaveCount(0)
  await expect(publication).toHaveAttribute('open', '')
  await expect(trigger).toBeFocused()
  await expect.poll(() => dialog.evaluate(node => node.scrollTop)).toBe(originalTop)
  await trigger.evaluate((node: HTMLButtonElement) => node.click())
  await editor.getByLabel('書籍備註').fill('取消的草稿')
  page.once('dialog', prompt => prompt.accept())
  await editor.getByLabel('書籍備註').press('Escape')
  await expect(editor).toHaveCount(0)
  await expect(publication).toHaveAttribute('open', '')
  await expect(trigger).toBeFocused()
  await expect.poll(() => dialog.evaluate(node => node.scrollTop)).toBe(originalTop)
  await page.getByRole('button', { name: '關閉', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(search).toHaveValue('直接編輯')
  await page.reload()
  await page.getByRole('button', { name: '書庫', exact: true }).click()
  await page.locator('.book-cover-open').first().click()
  await page.getByRole('button', { name: '編輯書籍', exact: true }).click()
  await expect(page.getByLabel('書籍字數')).toHaveValue('123456')
  await expect(page.locator('.book-form').getByRole('textbox', { name: '書籍備註', exact: true })).toHaveValue('https://example.com/' + 'longnote'.repeat(40))
})

test('mobile book fields scroll without losing the save and cancel actions', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 780 })
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  const dialog = page.getByRole('dialog')
  const fields = dialog.getByRole('group', { name: '書籍資料欄位' })
  const save = dialog.getByRole('button', { name: '儲存', exact: true })
  const cancel = dialog.getByRole('button', { name: '取消', exact: true })
  const assertActionsInView = async () => {
    for (const button of [save, cancel]) {
      const bounds = await button.boundingBox()
      expect(bounds!.y).toBeGreaterThanOrEqual(0)
      expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(780)
    }
  }
  await assertActionsInView()
  await dialog.getByLabel('出版書名', { exact: true }).fill('固定儲存列測試')
  await dialog.getByText('原文書名、譯者與繪者', { exact: true }).click()
  await dialog.getByLabel('譯者（每行一位）').fill('測試譯者')
  await dialog.getByLabel('書籍備註').fill('長表單末端的備註')
  const scrollArea = await fields.evaluate(node => {
    node.scrollTop = node.scrollHeight
    return { content: node.scrollHeight, visible: node.clientHeight }
  })
  expect(scrollArea.content).toBeGreaterThan(scrollArea.visible)
  await expect.poll(() => fields.evaluate(node => node.scrollTop)).toBeGreaterThan(0)
  await assertActionsInView()
  await expect.poll(() => dialog.evaluate(node => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(1)
  await save.click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('heading', { name: '固定儲存列測試', exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '書庫', exact: true }).click()
  await page.locator('.book-cover-open').first().click()
  await page.getByRole('button', { name: '編輯書籍', exact: true }).click()
  await expect(page.locator('.book-form').getByRole('textbox', { name: '書籍備註', exact: true })).toHaveValue('長表單末端的備註')
  await page.getByText('原文書名、譯者與繪者', { exact: true }).click()
  await expect(page.getByLabel('譯者（每行一位）')).toHaveValue('測試譯者')
})

