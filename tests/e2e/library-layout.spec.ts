import { expect, test } from './fixtures'

for (const width of [360, 1280]) {
 test(`compact shelf and list preserve search and filters after single-book save and cancel at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/')
  for (const title of ['封面書架測試', '另一個書目']) {
   await page.getByRole('button', { name: '新增書籍', exact: true }).click()
   await page.getByRole('button', { name: '輸入書名', exact: true }).click()
   await page.getByLabel('出版書名', { exact: true }).fill(title)
   await page.getByRole('button', { name: '儲存', exact: true }).click()
  }
  await expect(page.getByRole('heading', { name: '書庫', exact: true })).toHaveCount(0)
  const filter = page.getByRole('button', { name: '書庫篩選', exact: true })
  const count = page.getByRole('status', { name: '書庫符合筆數', exact: true })
  await expect(filter).toHaveAttribute('aria-expanded', 'false')
  await expect(page.getByLabel('依閱讀狀態篩選')).toBeHidden()
  await expect(count).toHaveCount(0)
  await filter.click()
  await expect(count).toHaveText('2／2 本')
  const search = page.getByRole('searchbox', { name: '搜尋書庫' })
  await search.fill('封面書架')
  const complete = page.getByLabel('依資料完整度篩選')
  await complete.selectOption('incomplete')
  await expect(page.locator('.book-row')).toHaveCount(1)
  await expect(page.locator('.book-completeness')).toHaveCount(0)
  await page.getByRole('button', { name: '清單模式', exact: true }).click()
  await expect(page.locator('.cover-library .book-cover, .cover-library .book-progress')).toHaveCount(0)
  await expect(page.locator('.library-list-title')).toHaveText('封面書架測試')
  await expect(page.locator('.library-list-authors')).toHaveText('作者未設定')
  await expect(count).toHaveText('1／2 本')
  await filter.click()
  await expect(count).toHaveCount(0)
  await expect(search).toHaveValue('封面書架')
  await page.getByRole('button', { name: '開啟《封面書架測試》', exact: true }).click()
  await expect(page.getByRole('dialog')).not.toContainText('資料待補：')
  await expect(page.getByRole('dialog').getByRole('img', { name: 'ISBN待編輯', exact: true })).toBeVisible()
  await page.getByLabel('書籍閱讀狀態').selectOption('planned')
  await expect(page.getByLabel('書籍閱讀狀態')).toBeEnabled()
  await page.getByRole('button', { name: '編輯我的分類', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '編輯我的分類與標籤', exact: true })).toBeVisible()
  await expect(page.getByLabel('出版書名', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('搜尋書籍來源', { exact: true })).toBeVisible()
  await page.getByRole('combobox', { name: '類型', exact: true }).selectOption('webNovel')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await expect(page.locator('.book-form').getByRole('status')).toHaveText('已儲存，可繼續編輯。')
  await page.locator('.book-form').getByRole('button', { name: '完成', exact: true }).click()
  await expect(page.locator('.book-detail')).toContainText('類型｜網文')
  await page.getByRole('button', { name: '編輯書籍', exact: true }).click()
  await expect(page.getByRole('combobox', { name: '類型', exact: true })).toHaveCount(0)
  await expect(page.getByLabel('搜尋標籤', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('搜尋書籍來源', { exact: true })).toHaveCount(0)
  await page.getByLabel('出版書名', { exact: true }).fill('不應儲存')
  page.once('dialog', dialog => dialog.accept())
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('dialog').getByRole('heading', { name: '《封面書架測試》', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '關閉', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(search).toHaveValue('封面書架')
  await filter.click()
  await expect(page.getByRole('button', { name: '清單模式', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(complete).toHaveValue('incomplete')
  await page.getByLabel('依閱讀狀態篩選').selectOption('planned')
  await expect(page.locator('.book-row')).toHaveCount(1)
  await expect(count).toHaveText('1／2 本')
  await complete.selectOption('類型')
  await expect(page.locator('.book-row')).toHaveCount(0)
  await complete.selectOption('出版社')
  await expect(page.locator('.book-row')).toHaveCount(1)
  await page.getByRole('button', { name: '封面模式', exact: true }).click()
  await expect(page.locator('.cover-library .book-progress')).toHaveCount(1)
  await complete.press('Escape')
  await expect(filter).toBeFocused()
  await expect(filter).toHaveAttribute('aria-expanded', 'false')
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await page.reload()
  await page.getByRole('button', { name: '書庫', exact: true }).click()
  await page.getByRole('button', { name: '開啟《封面書架測試》', exact: true }).click()
  await expect(page.locator('.book-detail')).toContainText('類型｜網文')
  await expect(page.getByLabel('書籍閱讀狀態')).toHaveValue('planned')
 })
}
