import { expect, test } from './fixtures'

for (const width of [360, 1024]) test(`editor stays narrow and grows text fields only for real content at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍', exact: true }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('合輯合成書')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: '開啟《合輯合成書》', exact: true }).click()
  await page.getByRole('button', { name: '編輯書籍資料', exact: true }).click()
  const editor = page.locator('.book-form--expanded'), fields = editor.getByRole('group', { name: '書籍資料欄位' })
  expect((await editor.boundingBox())!.width).toBeLessThanOrEqual(720)
  const authors = editor.getByLabel('作者（每行一位）', { exact: true }), title = editor.getByLabel('出版書名', { exact: true })
  expect((await authors.boundingBox())!.height).toBeLessThanOrEqual(60)
  const tools = editor.getByRole('group', { name: '圖片操作', exact: true })
  expect(await tools.locator('button').allTextContents()).toEqual(['搜尋', '上傳', '貼上'])
  const lookup = editor.getByRole('region', { name: '搜尋並補全書籍資料', exact: true })
  await expect(lookup.getByLabel('查詢書名', { exact: true })).toHaveCount(0)
  await lookup.getByRole('button', { name: '補資料', exact: true }).click()
  await expect(lookup.getByLabel('查詢書名', { exact: true })).toHaveValue('合輯合成書')
  await lookup.getByRole('button', { name: '關閉查詢', exact: true }).click()
  await expect(title).toHaveValue('合輯合成書')
  const names = Array.from({ length: 30 }, (_, i) => `合輯作者${i + 1}`).join('\n')
  const longTitle = '合輯與長書名自動換行測試'.repeat(10)
  await title.fill(longTitle)
  await authors.fill(names)
  expect((await title.boundingBox())!.height).toBeGreaterThan(60)
  expect((await authors.boundingBox())!.height).toBeGreaterThan(600)
  expect((await editor.getByRole('img', { name: '尚未設定封面', exact: true }).boundingBox())!.height).toBeLessThanOrEqual(90)
  expect(await authors.evaluate(el => el.scrollHeight - el.clientHeight)).toBeLessThanOrEqual(1)
  expect(await fields.evaluate(el => el.scrollWidth - el.clientWidth)).toBeLessThanOrEqual(1)
  await editor.screenshot({ path: test.info().outputPath(`adaptive-authors-${width}.png`) })
  await editor.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: '編輯書籍資料', exact: true }).click()
  await expect(authors).toHaveValue(names)
  await expect(title).toHaveValue(longTitle)
  expect((await authors.boundingBox())!.height).toBeGreaterThan(600)
  await authors.fill('合輯作者1')
  await title.fill('短書名')
  expect((await authors.boundingBox())!.height).toBeLessThanOrEqual(60)
  expect((await title.boundingBox())!.height).toBeLessThanOrEqual(60)
  await fields.evaluate(el => { el.scrollTop = 0 })
  await editor.screenshot({ path: test.info().outputPath(`dense-editor-${width}.png`) })
})
