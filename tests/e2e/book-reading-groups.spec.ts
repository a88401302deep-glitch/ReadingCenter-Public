import { expect, test } from './fixtures'

for (const width of [360, 1280]) test(`book reading groups stay separate and use compact rows at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍', exact: true }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('分次閱讀驗收')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: '開啟《分次閱讀驗收》', exact: true }).click()
  const status = page.getByLabel('書籍閱讀狀態')
  const statusLayout = await status.evaluate(node => {
    const label = node.closest('label')!, select = node.getBoundingClientRect(), parent = label.getBoundingClientRect()
    return { wrap: getComputedStyle(label).flexWrap, left: select.left - parent.left, height: parent.height, controlHeight: select.height }
  })
  expect(statusLayout.wrap).toBe('nowrap')
  expect(statusLayout.left).toBeGreaterThan(0)
  expect(statusLayout.height).toBeLessThanOrEqual(statusLayout.controlHeight + 1)
  await expect(page.getByText('修改狀態／重讀', { exact: true })).toHaveCount(0)
  const totals = page.locator('.book-reading-totals')
  await expect(totals.getByText('總閱讀時長', { exact: true })).toBeVisible()
  expect(await totals.evaluate(node => node.parentElement && getComputedStyle(node.parentElement).gridTemplateColumns.split(' ').length)).toBe(1)

  await page.getByRole('button', { name: '更新未分次紀錄（0）', exact: true }).click()
  await page.getByRole('button', { name: '新增紀錄', exact: true }).click()
  await page.locator('.record-form').getByLabel('開始時間').fill('2026-10-01T10:30')
  await page.locator('.record-form').getByLabel('閱讀時間（分鐘）').fill('7')
  await page.locator('.record-form').getByRole('button', { name: '儲存', exact: true }).click()
  await expect(page.locator('.record-form')).toHaveCount(0)
  await page.getByRole('button', { name: '更新未分次紀錄（1）', exact: true }).click()

  await page.getByRole('button', { name: '新增一次閱讀', exact: true }).click()
  const form = page.locator('.cycle-form')
  await form.getByRole('combobox').selectOption('completed')
  await form.getByLabel('完讀日期', { exact: true }).fill('2026-10-02')
  await form.getByLabel('整次閱讀累計分鐘').fill('100')
  await form.getByLabel('閱讀天數', { exact: true }).fill('3')
  await form.getByRole('button', { name: '儲存', exact: true }).click()
  await expect(form).toHaveCount(0)
  const first = page.getByRole('region', { name: '第 1 次閱讀', exact: true })
  await expect(first.getByText('2026-10-02', { exact: true })).toBeVisible()
  await expect(first.getByText('100 分鐘', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '新增一次閱讀', exact: true }).click()
  await form.getByLabel('開始時間', { exact: true }).fill('2026-10-02T10:30')
  await form.getByRole('button', { name: '儲存', exact: true }).click()
  await expect(form).toHaveCount(0)
  const second = page.getByRole('region', { name: '第 2 次閱讀', exact: true })
  await second.getByRole('button', { name: '更新閱讀紀錄（0）', exact: true }).click()
  await page.getByRole('button', { name: '新增紀錄', exact: true }).click()
  await page.locator('.record-form').getByLabel('開始時間').fill('2026-10-02T10:30')
  await page.locator('.record-form').getByLabel('閱讀時間（分鐘）').fill('15')
  await page.locator('.record-form').getByLabel('目前進度').fill('40')
  await page.locator('.record-form').getByRole('button', { name: '儲存', exact: true }).click()
  await expect(page.locator('.record-form')).toHaveCount(0)
  await second.getByRole('button', { name: '更新閱讀紀錄（1）', exact: true }).click()
  await expect(second.locator('.cycle-facts').getByText('40%', { exact: true })).toBeVisible()
  await expect(first).not.toContainText('40%')
  await expect(first.getByText('100 分鐘', { exact: true })).toBeVisible()
  await second.getByText('第 2 次閱讀明細（1）', { exact: true }).click()
  await expect(second.locator('.cycle-record-rows')).toContainText('15 分鐘')
  await expect(page.getByRole('region', { name: '未分次紀錄', exact: true }).getByRole('button', { name: '更新未分次紀錄（1）', exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await second.getByRole('button', { name: '更新閱讀紀錄（1）', exact: true }).click()
  await page.getByRole('button', { name: '標記完讀', exact: true }).click()
  const completion = page.getByRole('dialog', { name: '第 2 次閱讀：標記完讀', exact: true })
  await completion.getByLabel('完讀日期', { exact: true }).fill('2026-10-03')
  await completion.getByRole('button', { name: '取消', exact: true }).click()
  await expect(second.getByText('閱讀中', { exact: true })).toBeVisible()
  // Pointer interaction with the separate dialog closes the update popover.
  await second.getByRole('button', { name: '更新閱讀紀錄（1）', exact: true }).click()
  await page.getByRole('button', { name: '標記完讀', exact: true }).click()
  await completion.getByLabel('完讀日期', { exact: true }).fill('2026-10-03')
  await completion.getByRole('button', { name: '確認完讀', exact: true }).click()
  await expect(completion).toHaveCount(0)
  await expect(second.getByText('已讀完', { exact: true })).toBeVisible()
  await expect(second.getByText('2026-10-03', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByRole('button', { name: '書庫', exact: true }).click()
  await page.getByRole('button', { name: '開啟《分次閱讀驗收》', exact: true }).click()
  await expect(first.getByText('100 分鐘', { exact: true })).toBeVisible()
  await expect(second.locator('.cycle-facts').getByText('40%', { exact: true })).toBeVisible()
  await expect(second.getByText('2026-10-03', { exact: true })).toBeVisible()
})
