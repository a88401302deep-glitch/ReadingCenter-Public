import { expect, test, enterManagement } from './fixtures'

for (const width of [360, 1440]) test(`quiet book browsing keeps three entries, readable content and a sans-serif title at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/')
  const createBook = page.getByRole('button', { name: '新增書籍', exact: true })
  await expect(createBook).toHaveText('新增書籍')
  expect(await createBook.evaluate(node => node.getBoundingClientRect().height)).toBeGreaterThanOrEqual(44)
  await page.screenshot({ path: test.info().outputPath(`create-entry-${width}.png`) })
  await page.getByRole('button', { name: '新增書籍', exact: true }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  expect(await page.locator('.book-editor-heading h2').evaluate(node => getComputedStyle(node).fontFamily)).toContain('ui-rounded')
  await expect(page.getByRole('button', { name: '離開書籍編輯', exact: true })).toBeInViewport()
  await expect(page.getByRole('button', { name: '儲存', exact: true })).toBeInViewport()
  await page.screenshot({ path: test.info().outputPath(`create-book-${width}.png`) })
  await page.getByLabel('出版書名', { exact: true }).fill('沿著海岸，慢慢讀完這個世界')
  await page.getByLabel('作者（每行一位）', { exact: true }).fill('林予晴（合成資料）')
  await page.getByLabel('出版社', { exact: true }).fill('海岸書房（合成資料）')
  await page.getByLabel('出版日期或年份').fill('2025-04-18')
  await page.getByLabel('書籍備註').fill('此畫面使用合成書籍，不包含私人資料。')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: '開啟《沿著海岸，慢慢讀完這個世界》', exact: true }).click()
  const view = page.locator('.book-detail-view')
  await expect(view.locator('.book-detail-tools')).toHaveCount(0)
  const shades = await view.locator('.book-detail-book-card, .book-detail-reading, .reading-content-manager').evaluateAll(nodes => nodes.map(node => getComputedStyle(node).backgroundColor))
  expect(new Set(shades).size).toBe(3)
  const headers = view.locator('.book-card-heading, .book-detail-reading > .book-detail-panel-heading, .reading-content-manager > .section-heading')
  const titleStyles = await headers.evaluateAll(nodes => nodes.map(node => {
    const title = node.querySelector('h3')!, style = getComputedStyle(title)
    return { background: getComputedStyle(node).backgroundColor, weight: style.fontWeight, family: style.fontFamily, height: node.getBoundingClientRect().height }
  }))
  expect(titleStyles).toHaveLength(3)
  expect(new Set(titleStyles.map(style => style.background)).size).toBe(3)
  for (const style of titleStyles) {
    expect(style.background).not.toBe('rgba(0, 0, 0, 0)')
    expect(style.weight).toBe('700')
    expect(style.family).toContain('ui-rounded')
    expect(style.height).toBeGreaterThanOrEqual(width <= 640 ? 64 : 76)
  }
  if (width >= 1024) expect(Math.max(...titleStyles.map(s => s.height)) - Math.min(...titleStyles.map(s => s.height))).toBeLessThanOrEqual(1)
  await expect(view.getByRole('button')).toHaveCount(3)
  for (const button of await view.getByRole('button').all()) {
    expect(await button.evaluate(node => getComputedStyle(node).borderTopWidth)).toBe('1px')
    expect(await button.evaluate(node => getComputedStyle(node).backgroundColor)).not.toBe('rgba(0, 0, 0, 0)')
  }
  const manageBook = view.getByRole('button', { name: '編輯書籍資料', exact: true })
  expect(await manageBook.evaluate(node => getComputedStyle(node).borderTopWidth)).toBe('1px')
  expect(await manageBook.evaluate(node => getComputedStyle(node).backgroundColor)).not.toBe('rgba(0, 0, 0, 0)')
  await manageBook.click()
  const directEditor = page.getByRole('dialog', { name: '編輯書籍', exact: true })
  await expect(directEditor.getByLabel('查詢書名', { exact: true })).toBeVisible()
  await expect(directEditor.getByLabel('出版書名', { exact: true })).toBeEditable()
  await expect(directEditor.getByRole('button', { name: '儲存', exact: true })).toBeInViewport()
  await directEditor.screenshot({ path: test.info().outputPath(`direct-editor-${width}.png`) })
  await directEditor.getByRole('button', { name: '離開書籍編輯', exact: true }).click()
  await enterManagement(page, '閱讀')
  await page.getByRole('button', { name: '更新未分次紀錄（0）', exact: true }).click()
  await page.getByRole('button', { name: '新增紀錄', exact: true }).click()
  const createRecord = page.getByRole('button', { name: '新增紀錄', exact: true })
  expect(await createRecord.evaluate(node => getComputedStyle(node).backgroundImage)).toContain('linear-gradient')
  expect(await createRecord.evaluate(node => node.getBoundingClientRect().height)).toBeGreaterThanOrEqual(44)
  await expect(page.locator('.record-form').getByRole('button', { name: '儲存', exact: true })).toBeVisible()
  await page.locator('.record-form').scrollIntoViewIfNeeded()
  await page.screenshot({ path: test.info().outputPath(`create-record-${width}.png`) })
  await page.getByLabel('開始時間', { exact: true }).fill('2026-10-02T10:30')
  await page.getByLabel('閱讀時間（分鐘）').fill('45')
  await page.getByLabel('目前進度', { exact: true }).fill('62')
  await page.locator('.record-form').getByRole('button', { name: '儲存', exact: true }).click()
  await expect(page.locator('.record-form')).toHaveCount(0)
  await page.getByRole('button', { name: '完成閱讀編輯', exact: true }).click()
  await enterManagement(page, '心得')
  await page.getByRole('button', { name: '短評', exact: true }).click()
  await page.getByLabel('短評內容', { exact: true }).fill('喜歡那些沿途停下來的片刻，讓日常重新有了輪廓。')
  await expect(page.getByRole('button', { name: '完成心得編輯' })).toBeDisabled()
  await page.locator('.content-form').getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: '完成心得編輯', exact: true }).click()
  await expect(view.getByRole('button')).toHaveCount(3)
  await expect(page.getByRole('region', { name: '未分次閱讀明細' })).toContainText('45 分鐘')
  await expect(page.getByText('喜歡那些沿途停下來的片刻，讓日常重新有了輪廓。', { exact: true })).toBeVisible()
  await expect(view.locator('details')).toHaveCount(0)
  await expect(view.getByRole('combobox')).toHaveCount(0)
  const title = view.locator('.book-detail-introduction h3')
  expect(await title.evaluate(node => getComputedStyle(node).fontFamily)).toContain('ui-rounded')
  expect(await title.evaluate(node => getComputedStyle(node).fontWeight)).toBe('600')
  expect(await page.locator('.modal-header h2').evaluate(node => getComputedStyle(node).fontFamily)).toContain('ui-rounded')
  await expect.poll(() => page.getByRole('dialog').evaluate(node => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(1)
  await page.getByRole('dialog').evaluate(node => { node.scrollTop = 0 })
  await page.getByRole('dialog').screenshot({ path: test.info().outputPath(`quiet-browsing-${width}.png`) })
})
