import { expect, test, enterManagement } from './fixtures'

for (const width of [360, 1440]) test(`quiet book browsing keeps three entries, readable content and a sans-serif title at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍', exact: true }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('沿著海岸，慢慢讀完這個世界')
  await page.getByLabel('作者（每行一位）', { exact: true }).fill('林予晴（合成資料）')
  await page.getByLabel('出版社', { exact: true }).fill('海岸書房（合成資料）')
  await page.getByLabel('出版日期或年份').fill('2025-04-18')
  await page.getByLabel('書籍備註').fill('此畫面使用合成書籍，不包含私人資料。')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: '開啟《沿著海岸，慢慢讀完這個世界》', exact: true }).click()
  const view = page.locator('.book-detail-view')
  await expect(view.getByRole('button')).toHaveCount(3)
  await enterManagement(page, '閱讀')
  await page.getByRole('button', { name: '更新未分次紀錄（0）', exact: true }).click()
  await page.getByRole('button', { name: '新增紀錄', exact: true }).click()
  await page.getByLabel('開始時間', { exact: true }).fill('2026-10-02T10:30')
  await page.getByLabel('閱讀時間（分鐘）').fill('45')
  await page.getByLabel('目前進度', { exact: true }).fill('62')
  await page.locator('.record-form').getByRole('button', { name: '儲存', exact: true }).click()
  await expect(page.locator('.record-form')).toHaveCount(0)
  await page.getByRole('button', { name: '完成閱讀管理', exact: true }).click()
  await enterManagement(page, '心得')
  await page.getByRole('button', { name: '短評', exact: true }).click()
  await page.getByLabel('短評內容', { exact: true }).fill('喜歡那些沿途停下來的片刻，讓日常重新有了輪廓。')
  await expect(page.getByRole('button', { name: '完成心得管理' })).toBeDisabled()
  await page.locator('.content-form').getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: '完成心得管理', exact: true }).click()
  await expect(view.getByRole('button')).toHaveCount(3)
  await expect(page.getByRole('region', { name: '未分次閱讀明細' })).toContainText('45 分鐘')
  await expect(page.getByText('喜歡那些沿途停下來的片刻，讓日常重新有了輪廓。', { exact: true })).toBeVisible()
  await expect(view.locator('details')).toHaveCount(0)
  await expect(view.getByRole('combobox')).toHaveCount(0)
  const title = view.locator('.book-detail-introduction h3')
  expect(await title.evaluate(node => getComputedStyle(node).fontFamily)).toContain('ui-rounded')
  expect(await title.evaluate(node => getComputedStyle(node).fontWeight)).toBe('600')
  expect(await page.locator('.modal-header h2').evaluate(node => getComputedStyle(node).fontFamily)).toContain('ui-rounded')
  await expect.poll(() => page.getByRole('dialog').evaluate(node => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(1)
  await page.getByRole('dialog').evaluate(node => { node.scrollTop = 0 })
  await page.getByRole('dialog').screenshot({ path: test.info().outputPath(`quiet-browsing-${width}.png`) })
})
