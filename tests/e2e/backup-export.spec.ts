import { readFile } from 'node:fs/promises'
import { expect, test } from './fixtures'

test('device JSON download preserves a created book and does not change the library', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 780 })
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('合成下載測試')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: '管理', exact: true }).click()
  await page.getByRole('button', { name: '備份資料庫', exact: true }).click()
  const backup = page.getByRole('region', { name: '裝置資料備份' })
  await backup.getByRole('checkbox').uncheck()
  await backup.getByRole('button', { name: '準備資料 JSON' }).click()
  const link = backup.getByRole('link', { name: '下載備份' })
  await expect(link).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(1)
  const downloadPromise = page.waitForEvent('download')
  await link.click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/^readingcenter-device-.*\.json$/)
  const path = await download.path()
  expect(path).toBeTruthy()
  const value = JSON.parse(await readFile(path!, 'utf8'))
  expect(value).toMatchObject({ format: 'readingcenter-device-backup', version: 1, scope: 'device-data', counts: { books: 1 } })
  expect(value.data.books[0].title).toBe('合成下載測試')
  expect(value.data.sourceReadingDays).toEqual([])
  expect(value.data.readingContents).toEqual([])
  await page.getByRole('button', { name: '返回管理', exact: true }).click()
  await page.getByRole('button', { name: '匯入資料庫', exact: true }).click()
  const preview = page.getByRole('region', { name: '備份驗證與還原預覽' })
  await preview.getByLabel('選擇閱讀中心備份').setInputFiles(path!)
  await expect(preview.getByText('備份檔驗證完成，尚未還原。')).toBeVisible()
  await expect(preview.getByRole('row').filter({ has: page.getByRole('rowheader', { name: '書籍', exact: true }) })).toHaveText('書籍0010')
  await expect(preview.getByRole('button', { name: /還原/ })).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(1)
  value.data.books[0].bookNote = '合成還原後備註'
  await preview.getByLabel('選擇閱讀中心備份').setInputFiles({ name: 'restore.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(value)) })
  await expect(preview.getByRole('button', { name: '合併還原所選資料' })).toBeDisabled()
  await preview.getByLabel('合成下載測試（書籍／內容不同）').check()
  await preview.getByText('查看內容差異', { exact: true }).click()
  await expect(preview.getByText('備份："合成還原後備註"')).toBeVisible()
  await preview.getByRole('button', { name: '準備還原前資料備份' }).click()
  const beforeDownload = page.waitForEvent('download')
  await preview.getByRole('link', { name: '下載還原前資料備份' }).click()
  const beforePath = await (await beforeDownload).path()
  expect(JSON.parse(await readFile(beforePath!, 'utf8')).data.books[0].bookNote).not.toBe('合成還原後備註')
  await preview.getByLabel('已保存還原前備份，並核對所選資料的差異').check()
  await preview.getByRole('button', { name: '合併還原所選資料' }).click()
  await expect(preview.getByText(/已在此裝置合併還原 1 筆資料/)).toBeVisible()
  await expect(preview.getByRole('button', { name: '合併還原所選資料' })).toBeDisabled()
  await preview.getByLabel('選擇閱讀中心備份').setInputFiles({ name: 'repeat.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(value)) })
  await expect(preview.getByText('備份內容與目前資料相同，沒有需要還原的項目。')).toBeVisible()
  await preview.getByLabel('選擇閱讀中心備份').setInputFiles({ name: 'damaged.json', mimeType: 'application/json', buffer: Buffer.from('{broken') })
  await expect(preview.getByRole('alert')).toContainText('JSON')
  await expect(preview.getByRole('table')).toHaveCount(0)
  await page.getByRole('button', { name: '書庫', exact: true }).click()
  await expect(page.getByRole('heading', { name: '合成下載測試', exact: true })).toBeVisible()
})
