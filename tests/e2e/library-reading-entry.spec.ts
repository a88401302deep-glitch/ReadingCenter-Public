import { expect, test } from './fixtures'

test('mobile cover entry creates a record and short review that survive reload', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 780 })
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('清單新增閱讀測試')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('searchbox', { name: '搜尋書庫' }).fill('清單新增')
  await page.locator('.book-cover-open').first().click()
  await page.getByRole('button', { name: '更新未分次紀錄（0）' }).click()
  await page.getByRole('button', { name: '新增紀錄', exact: true }).click()
  const record = page.locator('.record-form')
  await record.getByLabel('開始時間').fill('2026-10-04T10:30')
  await record.getByLabel('閱讀時間（分鐘）').fill('25')
  await record.getByLabel('目前進度').fill('40')
  await expect(page.locator('.record-popover')).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(1)
  await record.getByRole('button', { name: '儲存', exact: true }).click()
  await expect(record).toHaveCount(0)
  await page.getByRole('button', { name: '更新未分次紀錄（1）' }).click()
  await page.getByRole('button', { name: '短評', exact: true }).click()
  const review = page.locator('.content-form')
  await review.getByLabel('短評內容').fill('直接在清單寫下心得')
  await review.getByRole('button', { name: '儲存', exact: true }).click()
  await expect(review).toHaveCount(0)
  await page.getByRole('button', { name: '關閉', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('searchbox', { name: '搜尋書庫' })).toHaveValue('清單新增')
  await page.reload()
  await page.getByRole('button', { name: '書庫', exact: true }).click()
  await page.getByRole('button', { name: /^開啟《/ }).click()
  await expect(page.getByText('直接在清單寫下心得', { exact: true })).toBeVisible()
  await page.getByText('閱讀明細', { exact: true }).click()
  const summary = page.getByRole('region', { name: '單書閱讀統計', exact: true })
  await expect(summary).toContainText('閱讀時間：25 分鐘')
  await expect(summary).toContainText('40%')
})

