import { expect, test } from './fixtures'
for (const width of [360, 1024]) test(`preset classifications can be picked, saved, filtered and cleared at ${width}px`, async ({page}) => {
 await page.setViewportSize({width,height:900})
 await page.goto('/')
 await page.getByRole('button',{name:'新增書籍',exact:true}).click()
 await page.getByRole('button',{name:'輸入書名',exact:true}).click()
 await page.getByLabel('出版書名',{exact:true}).fill('預設選項合成資料')
 await page.getByLabel('選擇分類',{exact:true}).selectOption({label:'文學小說'})
 await page.getByLabel('選擇分類',{exact:true}).selectOption({label:'社會科學'})
 await page.getByRole('combobox',{name:'類型',exact:true}).selectOption('novel')
 await page.getByLabel('選擇標籤',{exact:true}).selectOption({label:'推理'})
 await page.getByLabel('選擇標籤',{exact:true}).selectOption({label:'本格推理'})
 await page.getByRole('button',{name:'儲存',exact:true}).click()
 await page.getByRole('button',{name:'書庫',exact:true}).click()
 await page.getByRole('button',{name:'書庫篩選',exact:true}).click()
 await page.getByLabel('依分類篩選').selectOption({label:'文學小說'})
 await page.getByLabel('依標籤篩選').selectOption({label:'推理'})
 await expect(page.locator('.book-row')).toHaveCount(1)
 await page.getByRole('button',{name:'書庫篩選',exact:true}).click()
 await page.getByRole('button',{name:'開啟《預設選項合成資料》',exact:true}).click()
 await page.getByRole('button',{name:'編輯書籍資料',exact:true}).click()
 const editor=page.locator('.book-form--expanded')
 await expect(editor.getByRole('button',{name:'移除文學小說',exact:true})).toBeVisible()
 await expect(editor.getByRole('button',{name:'移除推理',exact:true})).toBeVisible()
 await expect(editor.getByRole('combobox',{name:'類型',exact:true})).toHaveValue('novel')
 await editor.getByLabel('選擇標籤',{exact:true}).scrollIntoViewIfNeeded()
 expect(await editor.evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1)
 await editor.screenshot({path:test.info().outputPath(`term-choices-${width}.png`)})
 for (const name of ['移除文學小說','移除社會科學','移除推理','移除本格推理']) await editor.getByRole('button',{name,exact:true}).click()
 await editor.getByRole('button',{name:'儲存',exact:true}).click()
 await page.getByRole('button',{name:'編輯書籍資料',exact:true}).click()
 await expect(editor.locator('.multi-select-values button')).toHaveCount(0)
})
