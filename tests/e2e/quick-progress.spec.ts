import { expect, test } from './fixtures'
for (const width of [360, 1280]) test(`home progress updates without duration or completion at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 780 })
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('進度快捷驗收')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.locator('.book-cover-open').first().click()
  await page.getByText('修改狀態／重讀', { exact: true }).click()
  await page.getByRole('button', { name: '手動補登（0）' }).click()
  await page.getByRole('button', { name: '新增紀錄', exact: true }).click()
  const record = page.locator('.record-form')
  await record.getByLabel('開始時間').fill('2026-10-04T10:30')
  await record.getByLabel('閱讀時間（分鐘）').fill('20')
  await record.getByLabel('目前進度').fill('20')
  await record.getByRole('button', { name: '儲存', exact: true }).click()
  await expect(record).toHaveCount(0)
  await page.getByRole('button', { name: '手動補登（1）' }).click()
  await page.getByRole('button', { name: '關閉', exact: true }).click()
  await page.getByRole('button', { name: '閱讀', exact: true }).click()
  const trigger = page.getByRole('button', { name: '更新《進度快捷驗收》進度', exact: true })
  await expect(trigger).toBeVisible()
  const hit = await trigger.boundingBox()
  expect(hit!.width).toBeGreaterThanOrEqual(44); expect(hit!.height).toBeGreaterThanOrEqual(44)
  const url = page.url()
  await trigger.focus()
  const top = await page.evaluate(() => scrollY)
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: '更新閱讀進度', exact: true })
  const value = dialog.getByLabel('目前進度', { exact: true })
  await expect(value).toHaveValue('20')
  await expect(page.locator('.cover-preview')).toHaveCount(0)
  const bounds = await dialog.boundingBox()
  expect(Math.abs(bounds!.y + bounds!.height / 2 - 390)).toBeLessThan(2)
  await value.fill('40')
  await dialog.getByLabel('紀錄時間').fill('2026-10-05T12:30')
  const save = dialog.getByRole('button', { name: '儲存進度', exact: true })
  await expect(save).toBeInViewport()
  await save.click()
  await expect(dialog).toHaveCount(0)
  const bar = page.locator('.recent-book-cards').getByRole('progressbar')
  await expect(bar).toHaveAttribute('value', '40')
  await expect(trigger).toBeFocused()
  expect(await page.evaluate(() => scrollY)).toBe(top); expect(page.url()).toBe(url)
  await trigger.click()
  await expect(value).toHaveValue('40')
  await value.fill('55')
  page.once('dialog', prompt => prompt.dismiss())
  await page.keyboard.press('Escape')
  await expect(value).toHaveValue('55')
  page.once('dialog', prompt => prompt.accept())
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(bar).toHaveAttribute('value', '40')
  await trigger.click()
  await dialog.getByLabel('進度單位').selectOption('page')
  await expect(value).toHaveValue('')
  await value.fill('40')
  await dialog.getByLabel('進度總數').fill('200')
  await dialog.getByLabel('紀錄時間').fill('2026-10-06T12:30')
  await save.click()
  await expect(dialog).toHaveCount(0)
  await expect(bar).toHaveAttribute('value', '20')
  await page.reload()
  await page.getByRole('button', { name: '閱讀', exact: true }).click()
  await trigger.click()
  await expect(dialog.getByLabel('進度單位')).toHaveValue('page')
  await expect(value).toHaveValue('40')
  await expect(dialog.getByLabel('進度總數')).toHaveValue('200')
  await dialog.getByLabel('進度單位').selectOption('percent')
  await value.fill('100')
  await dialog.getByLabel('紀錄時間').fill('2026-10-07T12:30')
  await save.click()
  await expect(dialog).toHaveCount(0)
  await expect(bar).toHaveAttribute('value', '100')
  await expect(trigger).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await page.getByRole('button', { name: '書庫', exact: true }).click()
  await page.locator('.book-cover-open').first().click()
  await expect(page.getByLabel('書籍閱讀狀態')).toHaveValue('reading')
  const summary = page.getByRole('region', { name: '單書閱讀統計' })
  await expect(summary).toContainText('20 分鐘'); await expect(summary).toContainText('否')
  await page.getByText('修改狀態／重讀', { exact: true }).click()
  await expect(page.getByRole('button', { name: '手動補登（4）' })).toBeVisible()
})
