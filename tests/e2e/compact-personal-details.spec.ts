import { expect, test } from './fixtures'
for(const width of [320,1024]) test(`personal book details use content height and wrapping tags at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:900})
 await page.goto('/')
 await expect(page.getByRole('button',{name:'新增書籍',exact:true})).toBeVisible()
 await page.evaluate(async()=>{
  const db=await new Promise<IDBDatabase>((resolve,reject)=>{const request=indexedDB.open('reading-center-local');request.onsuccess=()=>resolve(request.result);request.onerror=()=>reject(request.error)})
  await new Promise<void>((resolve,reject)=>{const tx=db.transaction('dictionaries','readwrite');tx.objectStore('dictionaries').put({id:'synthetic-readmoo',kind:'source',name:'讀墨',color:null,createdAt:'2026-10-30T00:00:00.000Z',updatedAt:'2026-10-30T00:00:00.000Z',revision:1,schemaVersion:1,provenance:{kind:'manual'}});tx.oncomplete=()=>resolve();tx.onerror=()=>reject(tx.error)})
  db.close()
 })
 await page.reload()
 await page.getByRole('button',{name:'新增書籍',exact:true}).click()
 await page.getByRole('button',{name:'輸入書名',exact:true}).click()
 await page.getByLabel('出版書名',{exact:true}).fill('個人資料緊湊合成書')
 await page.getByLabel('搜尋書籍來源',{exact:true}).fill('讀墨')
 await page.getByRole('option',{name:'讀墨',exact:true}).click()
 await page.getByLabel('選擇標籤',{exact:true}).selectOption({label:'哲學'})
 await page.getByRole('combobox',{name:'評分',exact:true}).selectOption('3')
 await page.getByLabel('書籍網址（每行一個）').fill('https://readmoo.com/book/synthetic')
 await page.getByRole('button',{name:'儲存',exact:true}).click()
 await page.getByRole('button',{name:'開啟《個人資料緊湊合成書》',exact:true}).click()
 const panel=page.getByRole('region',{name:'我的分類與標籤',exact:true}),meta=panel.locator('.book-detail-personal-meta')
 await panel.scrollIntoViewIfNeeded()
 await expect(panel).toContainText('讀墨')
 await expect(panel).toContainText('評分｜3／5')
 await expect(panel.locator('.book-detail-personal-tags')).toContainText('哲學')
 expect((await meta.boundingBox())!.height).toBeLessThanOrEqual(105)
 const source=panel.locator('.book-detail-source-tags'),label=(await source.locator('h4').boundingBox())!,badge=(await source.locator('.tag').boundingBox())!
 expect(Math.abs(label.y+label.height/2-badge.y-badge.height/2)).toBeLessThan(2)
 const link=panel.getByRole('link',{name:'開啟書籍來源：讀墨',exact:true})
 expect((await link.boundingBox())!.height).toBeGreaterThanOrEqual(44)
 expect(await panel.evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1)
 await panel.screenshot({path:test.info().outputPath(`personal-details-${width}.png`)})
 await page.getByRole('button',{name:'編輯書籍資料',exact:true}).click()
 for(const tag of ['推理','本格推理','都市傳說','奇幻','科幻','異世界','心理','成長']) await page.getByLabel('選擇標籤',{exact:true}).selectOption({label:tag})
 await page.getByRole('button',{name:'儲存',exact:true}).click()
 await expect(panel.locator('.book-detail-personal-tags .tag')).toHaveCount(9)
 expect(await panel.evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1)
})
