import { expect, test } from './fixtures'

test('a ReadingRecord updates book summary, reading totals and library statistics consistently', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('跨畫面一致性測試')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: /^開啟《/ }).click()
  await page.getByText('修改狀態／重讀', { exact: true }).click()
  await page.getByRole('button', { name: '手動補登（0）' }).click()
  await page.getByRole('button', { name: '新增紀錄' }).click()
  await page.getByLabel('開始時間').fill('2026-10-04T10:30')
  await page.getByLabel('閱讀時間（分鐘）').fill('30')
  await page.getByLabel('目前進度').fill('25')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  const summary = page.getByLabel('單書閱讀統計')
  await expect(summary).toContainText('30 分鐘')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: '閱讀', exact: true }).click()
  await expect(page.locator('.recent-book-list')).toContainText('跨畫面一致性測試')
  await expect(page.locator('.recent-book-list').getByRole('progressbar')).toHaveAttribute('value', '25')
  await expect(page.getByRole('button', { name: '統計', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '書庫', exact: true }).click()
  await page.getByRole('button', { name: /^開啟《/ }).click()
  await page.getByText('修改狀態／重讀', { exact: true }).click()
  await page.getByRole('button', { name: '手動補登（1）' }).click()
  await page.locator('.record-list li').first().getByRole('button', { name: '刪除' }).click()
  await page.getByRole('button', { name: '確認刪除' }).click()
  await expect(summary).toContainText('閱讀時間：未記錄')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '閱讀', exact: true }).click()
  await expect(page.locator('.recent-book-list')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '統計', exact: true })).toHaveCount(0)
})
