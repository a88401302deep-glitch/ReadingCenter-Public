import { expect, test, enterManagement } from './fixtures'

for (const width of [360, 1280]) {
 test(`reading notes edit and delete in centered dialogs without losing position at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 780 })
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('閱讀筆記同步測試')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: /^開啟《/ }).click()
  await enterManagement(page, '心得')
  await page.getByRole('button', { name: '短評', exact: true }).click()
  await page.getByLabel('短評內容').fill('剛新增的短評')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await enterManagement(page, '心得')
  await page.getByRole('button', { name: '長篇心得', exact: true }).click()
  await page.getByLabel('標題', { exact: true }).fill('長篇心得高度檢查')
  await page.getByLabel('長篇心得內容').fill(Array.from({ length: 15 }, (_, i) => `第${i + 1}行心得`).join('\n'))
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: '關閉' }).click()
  await page.getByRole('button', { name: '閱讀筆記', exact: true }).click()
  const longCard = page.locator('.note-card').filter({ has: page.getByRole('heading', { name: '長篇心得高度檢查' }) })
  await longCard.getByRole('button', { name: '編輯', exact: true }).click()
  const longDialog = page.getByRole('dialog', { name: '編輯長篇心得', exact: true })
  const longLines = await longDialog.getByLabel('內容', { exact: true }).evaluate(el => {
   const style = getComputedStyle(el)
   return (el.clientHeight - parseFloat(style.paddingTop) - parseFloat(style.paddingBottom)) / parseFloat(style.lineHeight)
  })
  expect(longLines).toBeGreaterThanOrEqual(10)
  expect(longLines).toBeLessThanOrEqual(15)
  await expect(longDialog.getByRole('button', { name: '儲存', exact: true })).toBeInViewport()
  await longDialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByText('剛新增的短評', { exact: true })).toBeVisible()

  // Synthetic local notes create a real scrollable stream; fixtures reject deployed hosts.
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: 'Excel', exact: true }).click()
  const csv = '書名,作者,短評\n' + Array.from({ length: 22 }, (_, i) => `筆記檢查 ${i + 1},作者甲,第${i + 1}則閱讀心得：${'這段文字用來驗證閱讀筆記的捲動位置。'.repeat(8)}`).join('\n')
  await page.getByLabel('選擇 Excel 或 CSV').setInputFiles({ name: 'synthetic-notes.csv', mimeType: 'text/csv', buffer: Buffer.from(csv) })
  await page.getByRole('button', { name: '確認匯入書籍', exact: true }).click()
  await expect(page.getByText('已新增 22 本，略過 0 本同名書籍。')).toBeVisible()
  await page.getByRole('button', { name: '閱讀筆記', exact: true }).click()
  const search = page.getByRole('searchbox', { name: '搜尋閱讀筆記' })
  await search.fill('筆記檢查')
  await page.getByLabel('依內容類型篩選').selectOption('shortReview')
  await expect(page.locator('.note-card')).toHaveCount(22)
  const item = page.locator('.note-card').filter({ has: page.getByRole('button', { name: '筆記檢查 8', exact: true }) })
  await item.scrollIntoViewIfNeeded()
  const edit = item.getByRole('button', { name: '編輯', exact: true })
  const coverBox = await item.locator('.book-cover').boundingBox()
  const editBox = await edit.boundingBox()
  expect(editBox!.y).toBeGreaterThanOrEqual(coverBox!.y + coverBox!.height)
  expect(editBox!.width).toBeGreaterThanOrEqual(44)
  expect(editBox!.height).toBeGreaterThanOrEqual(44)
  await expect(edit.locator('svg')).toBeVisible()
  const before = await page.evaluate(() => scrollY)
  expect(before).toBeGreaterThan(100)
  await edit.click()
  const dialog = page.getByRole('dialog', { name: '編輯短評', exact: true })
  await expect(dialog).toBeVisible()
  const visibleLines = await dialog.getByLabel('內容', { exact: true }).evaluate(el => {
   const style = getComputedStyle(el)
   return (el.clientHeight - parseFloat(style.paddingTop) - parseFloat(style.paddingBottom)) / parseFloat(style.lineHeight)
  })
  expect(visibleLines).toBeGreaterThanOrEqual(10)
  expect(visibleLines).toBeLessThanOrEqual(15)
  const box = await dialog.boundingBox()
  expect(Math.abs(box!.y + box!.height / 2 - 390)).toBeLessThanOrEqual(2)
  await expect(dialog.getByRole('button', { name: '儲存', exact: true })).toBeInViewport()
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(before)
  await dialog.getByRole('button', { name: '儲存', exact: true }).focus()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: '關閉', exact: true })).toBeFocused()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: '儲存', exact: true })).toBeFocused()
  await dialog.getByLabel('內容', { exact: true }).fill('第8則編輯後的閱讀心得')
  await dialog.getByRole('button', { name: '儲存', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(item.getByText('第8則編輯後的閱讀心得', { exact: true })).toBeVisible()
  await expect(edit).toBeFocused()
  await expect.poll(() => page.evaluate(() => scrollY)).toBe(before)
  await expect(search).toHaveValue('筆記檢查')
  await expect(page.getByLabel('依內容類型篩選')).toHaveValue('shortReview')

  await edit.click()
  await dialog.getByLabel('內容', { exact: true }).fill('不應儲存的草稿')
  page.once('dialog', confirmation => confirmation.dismiss())
  await dialog.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog.getByLabel('內容', { exact: true })).toHaveValue('不應儲存的草稿')
  page.once('dialog', confirmation => confirmation.accept())
  await dialog.getByRole('button', { name: '關閉', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(edit).toBeFocused()
  await expect(item.getByText('第8則編輯後的閱讀心得', { exact: true })).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)

  await page.reload()
  await page.getByRole('button', { name: '閱讀筆記', exact: true }).click()
  await search.fill('筆記檢查')
  await page.getByLabel('依內容類型篩選').selectOption('shortReview')
  await expect(item.getByText('第8則編輯後的閱讀心得', { exact: true })).toBeVisible()
  await item.getByRole('button', { name: '刪除', exact: true }).click()
  const deletion = page.getByRole('dialog', { name: '刪除閱讀筆記', exact: true })
  await deletion.getByRole('button', { name: '取消', exact: true }).click()
  await expect(item).toHaveCount(1)
  await item.getByRole('button', { name: '刪除', exact: true }).click()
  await deletion.getByRole('button', { name: '確認刪除', exact: true }).click()
  await expect(deletion).toHaveCount(0)
  await expect(item).toHaveCount(0)
  await expect(page.locator('.note-card')).toHaveCount(21)
  await expect(search).toBeFocused()
 })
}
