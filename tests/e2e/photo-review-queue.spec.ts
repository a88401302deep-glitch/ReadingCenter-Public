import { expect, test } from './fixtures'
test('multiple photos keep reviewed drafts after reload and only confirmed books enter the library', async ({ page, baseURL }) => {
 await page.setViewportSize({ width: 360, height: 780 })
 let requests = 0
 await page.route('**/api/v1/books/metadata?*', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ data: [{ id: 'bookrep:18250', source: '讀書共和國', title: '合成核對甲', authors: ['補全作者'], publisher: '補全出版社', isbn: '9781234567890', publishedOn: '2025', sourceUrl: 'https://www.bookrep.com.tw/?md=gwindex&cl=book&at=bookcontent&id=18250', coverUrl: null }] }) }))
 await page.route(`${baseURL}/api/v1/import/photo/book`, route => {
  requests++
  expect(route.request().headers()['content-type']).toBe('image/jpeg')
  return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ data: { books: requests === 1 ? [{ title:'合成照片甲',author:'合成作者',publisher:'',isbn:'',visibleText:'清單甲',completedOn:'2026-10-04',totalMinutes:'199' },{ title:'同張第二本',author:'',publisher:'',isbn:'',visibleText:'清單乙' }] : [{ title:'合成照片乙',author:'',publisher:'',isbn:'',visibleText:'另一張' }] } }) })
 })
 const open = async () => {
  await page.getByRole('button', { name: '管理', exact: true }).click()
  await page.getByRole('button', { name: '新增書籍', exact: true }).click()
  await page.getByRole('button', { name: '截圖', exact: true }).click()
 }
 await page.goto('/'); await open()
 const buffers = await page.evaluate(() => ['#ff0000','#0000ff'].map(color => { const canvas = document.createElement('canvas'); canvas.width = 20; canvas.height = 30; const context = canvas.getContext('2d')!; context.fillStyle = color; context.fillRect(0,0,20,30); return canvas.toDataURL('image/png').split(',')[1] }))
 await page.getByLabel('本批圖片來源').selectOption('圖書館')
 await page.getByLabel('選擇照片或截圖').setInputFiles(buffers.map((buffer,index) => ({ name: `photo-${index+1}.png`, mimeType: 'image/png', buffer: Buffer.from(buffer,'base64') })))
 await expect.poll(() => page.getByRole('region', { name:'拍照辨識書名' }).innerText()).toContain('已加入 2 張。尚未送出辨識。'); expect(requests).toBe(0)
 await page.getByRole('button', { name: '辨識所有待處理圖片' }).click()
 await expect(page.getByText('本批辨識已結束，請逐項核對後確認匯入。')).toBeVisible(); expect(requests).toBe(2)
 await expect(page.getByLabel('核對書名')).toHaveValue('合成照片甲')
 await page.getByLabel('核對書名').fill('合成核對甲')
 await expect(page.getByText('核對內容已保存。')).toBeVisible()
 await page.reload(); await open()
 await expect(page.getByLabel('核對書名')).toHaveValue('合成核對甲')
 await expect(page.locator('form').getByLabel('來源')).toHaveValue('圖書館')
 await expect(page.getByRole('button', { name: 'photo-2.png · 待確認' })).toBeVisible()
 expect(requests).toBe(2)
 await expect(page.getByRole('heading', { name: '合成核對甲', exact: true })).toBeVisible()
 await page.getByRole('button', { name: '帶入下列表單', exact: true }).click()
 await expect(page.getByLabel('核對出版社', { exact: true })).toHaveValue('補全出版社')
 await expect(page.getByLabel('核對書名', { exact: true })).toHaveValue('合成核對甲')
 await page.getByRole('button', { name: '確認匯入書籍資料' }).click()
 await expect(page.getByText('已確認新增《合成核對甲》。閱讀紀錄與封面未由此照片建立。')).toBeVisible()
 await expect(page.getByRole('button', { name: '候選 1：合成核對甲 · 書籍已確認' })).toBeVisible()
 await expect(page.getByLabel('完讀日期', { exact: true })).toHaveValue('2026-10-04')
 await expect(page.getByLabel('累計閱讀時間（分鐘）')).toHaveValue('199')
 await page.reload(); await open()
 await page.getByRole('button', { name: '候選 1：合成核對甲 · 書籍已確認' }).click()
 await expect(page.getByLabel('完讀日期', { exact: true })).toHaveValue('2026-10-04')
 await page.getByRole('button', { name: '確認匯入閱讀紀錄', exact: true }).click()
 await expect(page.getByText('已確認保存完讀日期與累計閱讀時間；未新增書籍或封面。')).toBeVisible()
 await expect(page.getByRole('button', { name: '候選 1：合成核對甲 · 書籍與閱讀紀錄已確認' })).toBeVisible()
 await page.getByRole('button', { name: '補全書籍資料與封面', exact: true }).click()
 await page.getByText('搜尋並補全書籍資料', { exact: true }).click()
 await page.getByRole('button', { name: '查詢書籍資料', exact: true }).click()
 await page.getByRole('button', { name: '核對《合成核對甲》', exact: true }).click()
 await page.getByRole('button', { name: '帶入下列表單', exact: true }).click()
 await expect(page.getByLabel('出版社', { exact: true })).toHaveValue('補全出版社')
 await page.getByRole('button', { name: '儲存', exact: true }).click()
 await expect(page.getByText('書籍資料已保存；沒有新增書籍或閱讀紀錄。')).toBeVisible()
 await expect(page.getByRole('button', { name: '候選 2：同張第二本 · 待確認' })).toBeVisible()
 await page.getByRole('button', { name: '候選 2：同張第二本 · 待確認' }).click()
 await expect(page.getByLabel('核對書名')).toHaveValue('同張第二本')
 await expect(page.getByRole('button', { name: 'photo-2.png · 待確認' })).toBeVisible()
 await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(1)
 await page.getByRole('button', { name: '書庫', exact: true }).click()
 await expect(page.getByRole('heading', { name: '合成核對甲', exact: true })).toBeVisible()
 await expect(page.getByRole('heading', { name: '合成照片乙', exact: true })).toHaveCount(0)
})
