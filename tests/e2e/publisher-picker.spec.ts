import { expect, test } from './fixtures'
for(const width of [360,1024]) test(`publisher can be reused, searched and manually corrected at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:900})
 await page.goto('/')
 const create=async(title:string)=>{
  await page.getByRole('button',{name:'新增書籍',exact:true}).click()
  await page.getByRole('button',{name:'輸入書名',exact:true}).click()
  await page.getByLabel('出版書名',{exact:true}).fill(title)
 }
 await create('出版社原始合成資料')
 await page.getByLabel('出版社',{exact:true}).fill('野人文化')
 await page.getByRole('button',{name:'儲存',exact:true}).click()
 await create('出版社選擇合成資料')
 await page.getByLabel('出版社',{exact:true}).fill('野人')
 await page.getByLabel('選擇既有出版社').selectOption({label:'野人文化'})
 await expect(page.getByLabel('出版社',{exact:true})).toHaveValue('野人文化')
 await page.getByRole('button',{name:'儲存',exact:true}).click()
 await page.getByRole('button',{name:'書庫',exact:true}).click()
 await page.getByRole('button',{name:'開啟《出版社選擇合成資料》',exact:true}).click()
 await page.getByRole('button',{name:'編輯書籍資料',exact:true}).click()
 const editor=page.locator('.book-form--expanded')
 await expect(editor.getByLabel('出版社',{exact:true})).toHaveValue('野人文化')
 await editor.getByLabel('出版社',{exact:true}).fill('人民文学出版社')
 await expect(editor.getByLabel('選擇既有出版社').locator('option')).toHaveCount(1)
 await editor.locator('.publisher-field').scrollIntoViewIfNeeded()
 expect(await editor.evaluate(el=>el.scrollWidth-el.clientWidth)).toBeLessThanOrEqual(1)
 await editor.screenshot({path:test.info().outputPath(`publisher-picker-${width}.png`)})
 await editor.getByRole('button',{name:'儲存',exact:true}).click()
 await page.getByRole('button',{name:'編輯書籍資料',exact:true}).click()
 await expect(editor.getByLabel('出版社',{exact:true})).toHaveValue('人民文学出版社')
 await expect(editor.getByLabel('選擇既有出版社').getByRole('option',{name:'人民文学出版社',exact:true})).toHaveCount(1)
 await editor.getByRole('button',{name:'取消',exact:true}).click()
 await page.getByRole('button',{name:'關閉',exact:true}).click()
 await page.getByRole('button',{name:'開啟《出版社原始合成資料》',exact:true}).click()
 await expect(page.locator('.book-publication-list')).toContainText('野人文化')
})
