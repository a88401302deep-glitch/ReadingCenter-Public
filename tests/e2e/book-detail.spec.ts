import { expect, test, enterManagement } from './fixtures'

for (const width of [320, 360, 768, 1024, 1280, 1440]) test(`single-book sections preserve library context and browser Back at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 780 })
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('單書頁測試')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  const search = page.getByRole('searchbox', { name: '搜尋書庫' })
  await search.fill('單書頁')
  await page.locator('.page-shell').evaluate((element) => { element.setAttribute('style', 'min-height: 1800px') })
  await page.evaluate(() => window.scrollTo(0, 420))
  const originalScrollTop = await page.evaluate(() => window.scrollY)
  await page.getByRole('button', { name: /^開啟《/ }).evaluate((element: HTMLButtonElement) => element.click())
  await expect(page.getByRole('dialog')).toBeVisible()
  await expect(page.getByRole('heading', { name: '《單書頁測試》', exact: true })).toBeVisible()
  await expect(page.locator('.book-detail-title')).toHaveCount(0)
  const coverLayout = page.locator('.book-detail-cover-layout')
  const cover = coverLayout.locator('.book-detail-cover')
  const coverBounds = (await cover.boundingBox())!
  const layoutBounds = (await coverLayout.boundingBox())!
  const titleBounds = (await coverLayout.locator('.book-detail-introduction').boundingBox())!
  const fine = await page.evaluate(() => matchMedia('(pointer:fine)').matches)
  if (width < 1024) {
    expect(coverBounds.width).toBeGreaterThanOrEqual(Math.min(320, layoutBounds.width) - 1)
    expect(Math.abs(coverBounds.x + coverBounds.width / 2 - layoutBounds.x - layoutBounds.width / 2)).toBeLessThan(1)
    expect(titleBounds.y).toBeGreaterThanOrEqual(coverBounds.y + coverBounds.height)
  } else {
    if (fine) { expect(coverBounds.width).toBeGreaterThanOrEqual(144); expect(coverBounds.width).toBeLessThanOrEqual(201) }
    else expect(coverBounds.width).toBe(240)
    const info = (await page.locator('.book-detail-information').boundingBox())!
    expect(info.x).toBeGreaterThan(coverBounds.x + coverBounds.width)
    expect(titleBounds.x).toBeGreaterThan(coverBounds.x + coverBounds.width)
    expect(Math.abs(titleBounds.y - coverBounds.y)).toBeLessThan(2)
  }
  await expect(page.locator('.book-detail-view details')).toHaveCount(0)
  await expect(page.locator('.book-detail-view').getByRole('button')).toHaveCount(3)
  await expect(coverLayout.getByRole('button', { name: '上傳', exact: true })).toHaveCount(0)
  const dialog = page.getByRole('dialog')
  const sidebar = dialog.locator('.book-detail-book-card')
  const reading = dialog.locator('.book-detail-view > .cycle-manager')
  const left = await sidebar.boundingBox(), right = await reading.boundingBox()
  if (width >= 1024) {
    expect((await dialog.boundingBox())!.width).toBeCloseTo(Math.min(1600, width - 64), 0)
    if (width >= 1280 || fine) {
      expect(right!.x).toBeGreaterThanOrEqual(left!.x + left!.width)
      expect(Math.abs(right!.y - left!.y)).toBeLessThanOrEqual(1)
    } else expect(right!.y).toBeGreaterThanOrEqual(left!.y + left!.height)
  } else {
    expect(right!.y).toBeGreaterThanOrEqual(left!.y + left!.height)
  }
  await dialog.screenshot({ path: test.info().outputPath(`book-detail-${width}.png`) })
  await expect(dialog.getByRole('region', { name: '書籍資料', exact: true })).toBeVisible()
  await expect(dialog.getByText('圖書分類', { exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('heading', { name: '標籤', exact: true })).toHaveCount(0)
  await expect(dialog.getByRole('region', { name: '閱讀紀錄', exact: true })).toBeVisible()
  await expect(dialog.getByRole('region', { name: '閱讀心得', exact: true })).toBeVisible()
  await expect(dialog.getByRole('region', { name: '我的分類與標籤', exact: true })).toHaveCount(0)
  await expect(dialog.locator('.book-detail-publication')).toHaveCount(0)
  for (const region of ['書籍資料', '閱讀紀錄', '閱讀心得']) {
    const panel = dialog.getByRole('region', { name: region, exact: true })
    const style = await panel.evaluate(node => { const s = getComputedStyle(node); return { border: parseFloat(s.borderTopWidth), radius: parseFloat(s.borderTopLeftRadius) } })
    expect(style.radius).toBe(['閱讀紀錄', '閱讀心得'].includes(region) ? 20 : 0)
    await expect(panel.locator('h3 svg').first()).toBeVisible()
  }
  await expect(dialog.getByText('匯入原始資料', { exact: true })).toHaveCount(0)
  await enterManagement(page, '書籍')
  const editor = page.locator('.book-form')
  await expect(editor.getByLabel('出版書名', { exact: true })).toHaveValue('單書頁測試')
  for (const label of ['作者（每行一位）', '譯者（每行一位）', '繪者／插畫者（每行一位）', '出版社', 'ISBN', '書籍字數']) await expect(editor.getByLabel(label, { exact: true })).toBeVisible()
  await editor.getByRole('button', { name: '取消', exact: true }).click()
  await expect(dialog.locator('.book-field-pending')).toHaveCount(0)
  await expect.poll(() => dialog.evaluate(node => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(1)
  await page.goBack()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(search).toHaveValue('單書頁')
  await expect.poll(() => page.evaluate(() => window.scrollY)).toBe(originalScrollTop)
  await expect(page.getByRole('heading', { name: '單書頁測試', exact: true })).toBeVisible()
})

