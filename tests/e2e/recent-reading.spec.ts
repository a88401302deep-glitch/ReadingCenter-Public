import { expect, test } from './fixtures'

test('a dated reading cycle appears without creating daily activities', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 780 })
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('只有閱讀週期的書')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: /^開啟《/ }).click()
  await page.getByText('修改狀態／重讀', { exact: true }).click()
  await page.getByRole('button', { name: '新增一次閱讀', exact: true }).click()
  await page.locator('.cycle-form').getByRole('combobox').selectOption('completed')
  await page.getByLabel('結束時間', { exact: true }).fill('2026-10-04T10:30')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await expect(page.getByText('已讀完', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '閱讀', exact: true }).click()
  const list = page.locator('.recent-book-cards')
  await expect(list).toContainText('只有閱讀週期的書')
  await expect(list).not.toContainText('閱讀時間未記錄')
  await expect(page.getByRole('region', { name: '閱讀統計與月曆', exact: true })).toHaveCount(0)
  await expect(list.getByRole('progressbar', { name: '已完讀', exact: true })).toHaveAttribute('value', '100')
  const completed = page.getByRole('region', { name: '最近讀完' })
  await expect(completed).toContainText('只有閱讀週期的書')
  await expect(page.getByRole('region', { name: '閱讀心得' })).toBeVisible()
  const timeline = page.getByRole('region', { name: '閱讀紀錄時間軸' })
  await expect(timeline).toHaveCount(0)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(1)
})

for (const width of [360, 1280]) test(`recent cover opens a centered lightbox over the page at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 780 })
  await page.route('**/test-preview-cover.svg', route => route.fulfill({ contentType: 'image/svg+xml', body: '<svg xmlns="http://www.w3.org/2000/svg" width="700" height="1000"><rect width="700" height="1000" fill="#EAC1CB"/><text x="100" y="200" font-size="60">Cover</text></svg>' }))
  await page.goto('/')
  const title = '手機最近閱讀' + '長書名測試'.repeat(8)
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill(title)
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.locator('.book-cover-open').first().click()
  await page.getByRole('button', { name: '編輯書籍', exact: true }).click()
  await page.getByText('封面路徑', { exact: true }).click()
  await page.getByLabel('封面檔案路徑').fill('/test-preview-cover.svg')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await expect(page.locator('.book-form')).toHaveCount(0)
  await page.getByText('修改狀態／重讀', { exact: true }).click()
  await page.getByRole('button', { name: '手動補登（0）' }).click()
  await page.getByRole('button', { name: '新增紀錄', exact: true }).click()
  const form = page.locator('.record-form')
  await form.getByLabel('開始時間').fill('2026-10-04T10:30')
  await form.getByLabel('閱讀時間（分鐘）').fill('20')
  await form.getByRole('button', { name: '儲存', exact: true }).click()
  await expect(form).toHaveCount(0)
  await page.getByRole('button', { name: '手動補登（1）' }).click()
  await page.getByRole('button', { name: '關閉', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: '閱讀', exact: true }).click()
  const list = page.locator('.recent-book-cards')
  await expect(list.getByRole('listitem')).toHaveCount(1)
  await expect(list).toContainText(title)
  await expect(list).not.toContainText('累計 20 分鐘')
  await expect(list.locator('.recent-book-cover')).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)).toBeLessThanOrEqual(1)
  const trigger = list.getByRole('button', { name: `放大《${title}》封面`, exact: true })
  await trigger.focus()
  const scroll = await page.evaluate(() => scrollY)
  await trigger.click()
  const preview = page.getByRole('dialog', { name: `《${title}》封面預覽` })
  await expect(preview).toBeVisible()
  const bounds = await preview.boundingBox()
  expect(bounds!.width).toBe(width); expect(bounds!.height).toBe(780)
  const cover = preview.getByRole('img', { name: `${title}封面`, exact: true })
  await expect(cover).toBeVisible()
  await expect.poll(() => cover.evaluate((node: HTMLImageElement) => node.naturalWidth)).toBe(700)
  const image = await cover.boundingBox()
  expect(image!.width).toBeLessThanOrEqual(width * .78 + 1)
  expect(image!.height).toBeLessThanOrEqual(780 * .78 + 1)
  expect(Math.abs(image!.x + image!.width / 2 - width / 2)).toBeLessThan(2)
  expect(Math.abs(image!.y + image!.height / 2 - 390)).toBeLessThan(2)
  expect(Math.abs(image!.width / image!.height - .7)).toBeLessThan(.01)
  const appearance = await preview.evaluate(node => ({
    surface: getComputedStyle(node).backgroundColor,
    backdrop: getComputedStyle(node, '::backdrop').backgroundColor
  }))
  expect(appearance.surface).toBe('rgba(0, 0, 0, 0)')
  expect(appearance.backdrop).toBe('rgba(40, 37, 34, 0.4)')
  await expect(preview.getByRole('button')).toHaveCount(1)
  await expect(preview.getByRole('button', { name: '前往書籍資料' })).toHaveCount(0)
  await expect(page.locator('.book-detail')).toHaveCount(0)
  await cover.click()
  await expect(preview).toHaveCount(0)
  await expect(trigger).toBeFocused()
  expect(await page.evaluate(() => scrollY)).toBe(scroll)
  await trigger.click()
  await preview.getByRole('button', { name: '關閉封面預覽' }).click({ position: { x: 8, y: 8 } })
  await expect(preview).toHaveCount(0)
  await expect(trigger).toBeFocused()
  expect(await page.evaluate(() => scrollY)).toBe(scroll)
  await trigger.click()
  await page.keyboard.press('Escape')
  await expect(preview).toHaveCount(0)
  await expect(trigger).toBeFocused()
})


