test('long imported metadata and notes fit a mobile book dialog without horizontal scrolling', async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 780 })
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('全A反派家的唯一omega幼崽' + 'LongTitle'.repeat(12))
  await page.getByLabel('書籍版本', { exact: true }).selectOption('ebook')
  await page.getByLabel('書籍備註').fill('https://example.com/' + 'unbroken'.repeat(45))
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: /^開啟《/ }).click()
  const dialog = page.getByRole('dialog')
  await dialog.locator('.book-detail-publication > summary').click()
  await expect(dialog.getByText('未指定｜電子書', { exact: true })).toBeVisible()
  await expect(dialog.getByText(/notion:dictionary:/)).toHaveCount(0)
  await expect.poll(() => dialog.evaluate((node) => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(1)
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(361)
  await page.getByRole('button', { name: '編輯書籍' }).click()
  await expect.poll(() => dialog.evaluate((node) => node.scrollWidth - node.clientWidth)).toBeLessThanOrEqual(1)
  await page.getByRole('button', { name: '取消', exact: true }).click()
  await page.getByRole('button', { name: '關閉' }).click()
  await expect(dialog).toHaveCount(0)
})

test('book source links can be saved, edited, and explicitly cleared', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '新增書籍' }).click()
  await page.getByRole('button', { name: '輸入書名', exact: true }).click()
  await page.getByLabel('出版書名', { exact: true }).fill('網址測試')
  await page.getByLabel('書籍網址（每行一個）').fill('https://example.com/book\nhttps://example.com/second')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await page.getByRole('button', { name: /^開啟《/ }).click()
  await page.locator('.book-detail-publication > summary').click()
  await expect(page.getByRole('link', { name: 'https://example.com/book', exact: true })).toHaveAttribute('href', 'https://example.com/book')
  await expect(page.getByRole('link', { name: 'https://example.com/second', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '編輯書籍' }).click()
  await page.getByLabel('書籍網址（每行一個）').fill('')
  await page.getByRole('button', { name: '儲存', exact: true }).click()
  await expect(page.getByRole('link', { name: 'https://example.com/book', exact: true })).toHaveCount(0)
  await page.reload()
  await page.getByRole('button', { name: '書庫', exact: true }).click()
  await page.getByRole('button', { name: /^開啟《/ }).click()
  await expect(page.getByRole('link', { name: 'https://example.com/second', exact: true })).toHaveCount(0)
})


